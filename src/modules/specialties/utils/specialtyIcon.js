const normalize = (text = '') =>
  text.normalize('NFD').replace(/[̀-ͯ]/g, '').toLowerCase();

export const specialtyIcon = (name) => {
  const key = normalize(name);
  const match = ICONS.find(([pattern]) => pattern.test(key));

  return match ? match[1] : Stethoscope;
};
